/** Writes src/lib/local-pay-data.ts from scripts/local-pay/local-pay.json (see refresh.py). */
import { writeFileSync } from "node:fs";
import { countriesInLocation } from "@/lib/country-match";
import data from "./local-pay.json";
type E = { country: string; [k: string]: unknown };
const rows = (data as E[]).map((e) => {
  const c = countriesInLocation(e.country);
  if (c.length !== 1) throw new Error(`no single country for ${e.country}: ${c}`);
  return { ...e, code: c[0] };
});
const body = rows.map((r) => "  " + JSON.stringify(r)).join(",\n");
writeFileSync("src/lib/local-pay-data.ts", `/**
 * Salary scales for locally recruited UN staff (General Service and National Officers), one entry
 * per duty station: annual net salary in the scale's currency, first step to the highest step
 * (long-service steps included), from the scale files published on the UN salary scale site
 * (LOCAL_PAY_SOURCE in src/lib/local-pay.ts). Generated by scripts/local-pay/refresh.py and
 * scripts/local-pay/write-data.ts; don't edit by hand.
 *
 * Fetched ${new Date().toISOString().slice(0, 10)}.
 */
import type { LocalPayStation } from "./local-pay";

export const LOCAL_PAY_FETCHED = "${new Date().toISOString().slice(0, 10)}";

export const LOCAL_PAY_STATIONS: LocalPayStation[] = [
${body},
];
`);
